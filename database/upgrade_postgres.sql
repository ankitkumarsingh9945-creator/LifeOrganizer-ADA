-- Additive schema for the web app's PostgreSQL deployment.

CREATE TABLE IF NOT EXISTS users (
 user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS groceries (
 grocery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 item_name VARCHAR(120) NOT NULL,
 category VARCHAR(80) NOT NULL DEFAULT 'Other',
 quantity VARCHAR(50) NOT NULL DEFAULT '1',
 purchased_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
   CHECK (purchased_status IN ('Pending','Purchased')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_grocery_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_grocery_user ON groceries(user_id);
CREATE INDEX IF NOT EXISTS idx_grocery_name ON groceries(item_name);

CREATE TABLE IF NOT EXISTS bills (
 bill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 bill_name VARCHAR(120) NOT NULL,
 amount DECIMAL(12,2) NOT NULL CHECK(amount >= 0),
 due_date DATE NOT NULL,
 payment_status VARCHAR(20) NOT NULL DEFAULT 'Unpaid' CHECK(payment_status IN ('Unpaid','Paid')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_bill_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_bill_user_due ON bills(user_id,due_date);

CREATE TABLE IF NOT EXISTS expenses (
 expense_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 category VARCHAR(80) NOT NULL,
 amount DECIMAL(12,2) NOT NULL CHECK(amount >= 0),
 expense_date DATE NOT NULL,
 notes VARCHAR(255),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_expense_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_expense_user_date ON expenses(user_id,expense_date);

CREATE TABLE IF NOT EXISTS documents (
 document_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 document_name VARCHAR(180) NOT NULL,
 category VARCHAR(80) NOT NULL DEFAULT 'Other',
 file_path VARCHAR(500),
 notes VARCHAR(255),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_document_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_document_user ON documents(user_id);

CREATE TABLE IF NOT EXISTS medicines (
 medicine_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 medicine_name VARCHAR(120) NOT NULL,
 dosage VARCHAR(80),
 reminder_time TIME NOT NULL,
 notes VARCHAR(255),
 CONSTRAINT fk_medicine_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_medicine_user_time ON medicines(user_id,reminder_time);

CREATE TABLE IF NOT EXISTS tasks (
 task_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 task_name VARCHAR(180) NOT NULL,
 deadline DATE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','In Progress','Completed')),
 priority SMALLINT NOT NULL DEFAULT 3 CHECK(priority BETWEEN 1 AND 5),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_task_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_task_user_priority ON tasks(user_id,priority);
CREATE INDEX IF NOT EXISTS idx_task_deadline ON tasks(user_id,deadline);

CREATE TABLE IF NOT EXISTS audit_logs (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 entity_name VARCHAR(50) NOT NULL,
 record_id BIGINT,
 action_name VARCHAR(30) NOT NULL,
 details VARCHAR(500),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_audit_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_audit_user_time ON audit_logs(user_id,created_at);

CREATE TABLE IF NOT EXISTS calendar_events (
 event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 event_title VARCHAR(180) NOT NULL,
 event_date DATE NOT NULL,
 event_time TIME,
 description VARCHAR(500),
 reminder_minutes INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_calendar_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_calendar_user_date ON calendar_events(user_id,event_date);

CREATE TABLE IF NOT EXISTS expense_budgets (
 budget_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 category VARCHAR(80) NOT NULL,
 month_start DATE NOT NULL,
 budget_amount DECIMAL(12,2) NOT NULL CHECK(budget_amount >= 0),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_budget_user_category_month UNIQUE(user_id,category,month_start),
 CONSTRAINT fk_budget_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminder_actions (
 action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL,
 reminder_key VARCHAR(190) NOT NULL,
 action_type VARCHAR(20) NOT NULL CHECK(action_type IN ('SNOOZE','COMPLETED')),
 snooze_until TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_reminder_action UNIQUE(user_id,reminder_key),
 CONSTRAINT fk_reminder_action_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
